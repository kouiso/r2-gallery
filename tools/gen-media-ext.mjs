// 一覧が拾う拡張子の表（worker/src/lib/media-ext.json）から Dart 側の表を生成する。
// `--check` は生成物が最新かだけ確かめる（CI の fast で回す）。
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const src = new URL("../worker/src/lib/media-ext.json", import.meta.url);
const out = new URL("../flutter/lib/src/webdl/listed_ext.g.dart", import.meta.url);

export function render(table) {
  const list = (xs) => xs.map((x) => `'${x}'`).join(", ");
  return `// GENERATED by tools/gen-media-ext.mjs from worker/src/lib/media-ext.json. 手で編集しない。
// 一覧が拾う拡張子。ここに無い拡張子で上げたキーは一覧に一生出てこない
// ignore_for_file: type=lint
library;

const listedImageExt = <String>[${list(table.image)}];
const listedVideoExt = <String>[${list(table.video)}];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render(JSON.parse(readFileSync(src, "utf8")));
  if (process.argv.includes("--check")) {
    if (readFileSync(out, "utf8") !== text) {
      console.error("listed_ext.g.dart が古い。node tools/gen-media-ext.mjs を実行する");
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
  }
}
